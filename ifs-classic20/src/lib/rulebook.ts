export function sectionPlainText(section: Section) {
  const parts = [section.number, section.title, section.kicker];
  for (const block of section.blocks) {
    if (block.type === "p" || block.type === "h3" || block.type === "formula") {
      parts.push(block.text);
    } else if (block.type === "note") {
      parts.push(block.title, block.text);
    } else if (block.type === "ul" || block.type === "ol") {
      parts.push(...block.items);
    } else if (block.type === "table") {
      parts.push(block.caption ?? "", ...block.headers, ...block.rows.flat());
    }
  }
  return parts.join("\n");
}
